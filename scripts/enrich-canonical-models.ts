export function enrichModels() {
  const modelsPath = resolve(__dirname, '../src/data/models.json');
  const existingModels: ModelRecord[] = JSON.parse(readFileSync(modelsPath, 'utf8'));

  const modelMap = new Map<string, ModelRecord>();

  // First place canonical models
  for (const model of canonicalModels) {
    modelMap.set(model.id, model);
  }

  // Then add/merge existing models
  for (const model of existingModels) {
    if (!modelMap.has(model.id)) {
      modelMap.set(model.id, model);
    } else {
      // Preserve any extra hosting offers from existing
      const canonical = modelMap.get(model.id)!;
      for (const offer of model.hostingOffers || []) {
        if (!canonical.hostingOffers.some((h) => h.hostId === offer.hostId)) {
          canonical.hostingOffers.push(offer);
        }
      }
    }
  }

  const merged = Array.from(modelMap.values());
  writeFileSync(modelsPath, JSON.stringify(merged, null, 2), 'utf8');
  console.log(`✅ Successfully enriched models.json! Total canonical & benchmark models: ${merged.length}`);
}

enrichModels();
